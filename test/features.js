import assert from 'node:assert/strict';
import {Room} from '../server/room.js';
import {C,MAPS,BOOST_PADS,arenaObjects,objectRect,hitRect,updateBoost,move} from '../shared/game.js';
const events=[];
const socket=()=>({readyState:1,send:raw=>events.push(JSON.parse(raw))});
const room=new Room('TEAM');clearInterval(room.iv);
try{
  const boost={energy:100,x:450,y:60,a:0,dU:0};
  updateBoost(boost,true,1);assert.equal(boost.energy,55);
  move(boost,1,0,.1,100,[]);assert.equal(boost.x,486,'boost movement speed');
  updateBoost(boost,true,2);assert.equal(boost.energy,0);assert.equal(boost.boost,false);
  updateBoost(boost,true,1);assert.equal(boost.boost,false,'holding empty boost cannot restart');
  updateBoost(boost,false,1);updateBoost(boost,true,.1);assert.ok(boost.boost,'release restores boost access');
  for(const map of Object.values(MAPS)){
    for(const [x,y] of BOOST_PADS)assert.ok(!map.obstacles.some(o=>hitRect(x,y,o,25)),'pads clear map cover');
    for(const object of arenaObjects())assert.ok(!map.obstacles.some(o=>hitRect(object.x,object.y,o,20)),'objects clear map cover');
  }
  const players=Array.from({length:4},(_,i)=>room.join(socket(),'P'+i,''));
  const host=players[0];
  room.configure(host,{map:'neon',minutes:1,target:5,mode:'2v2',difficulty:'hard'});
  assert.deepEqual(players.map(p=>p.team),[0,1,0,1]);
  const previous=room.settings;
  room.configure(host,{map:'neon',minutes:1,target:5,mode:'bad',difficulty:'easy'});
  assert.equal(room.settings,previous,'invalid extended settings rejected');
  for(const p of players)p.ready=true;
  room.start(host,Date.now());assert.equal(room.ph,'count');
  for(const p of players){p.sh=0;p.hp=100;p.al=true;p.x=450;p.y=60;}
  players[1].x=600;players[3].x=700;
  const bot={...host,id:99,x:510,y:60,in:{}};
  room.settings.difficulty='hard';room.driveBot(bot,3000);
  const hardError=Math.abs(bot.in.a);
  room.settings.difficulty='easy';room.driveBot(bot,3000);
  assert.ok(Math.abs(bot.in.a)>hardError,'easy bots have more aim error');
  assert.ok(Math.abs(bot.in.a)<1,'bots target enemies rather than nearer teammates');
  room.damage(players[2],25,host.id,1000);assert.equal(players[2].hp,100,'friendly fire disabled');
  room.damage(players[1],100,host.id,1000);assert.equal(host.k,1);assert.equal(players[1].al,false);
  assert.deepEqual(room.teamScores(),[1,0]);
  room.damage(host,100,host.id,1000);assert.equal(host.k,1,'self damage gives no score');
  room.spawn(host,2000,false);host.sh=0;host.x=450;host.y=60;
  const object=room.objects[0];
  room.bs=[{id:1,o:host.id,x:object.x,y:object.y-20,a:Math.PI/2,l:1,speed:740,damage:50}];
  room.sim(2100,1/C.TICK);assert.equal(object.hp,0,'bullets destroy cover');
  assert.ok(!room.obstacles().some(o=>JSON.stringify(o)===JSON.stringify(objectRect(object))));
  const barrel=room.objects.find(o=>o.type==='barrel');
  players[1].al=true;players[1].hp=20;players[1].x=barrel.x;players[1].y=barrel.y-30;players[1].sh=0;
  players[2].x=barrel.x;players[2].y=barrel.y-20;
  players[3].x=barrel.x;players[3].y=barrel.y+20;players[3].sh=10000;
  room.breakObject(barrel,host.id,2200);
  assert.equal(players[1].al,false,'barrel explosion damages enemies');
  assert.equal(players[2].hp,100,'explosion protects teammates');
  assert.equal(players[3].hp,100,'explosion respects spawn shield');
  const kills=host.k;room.breakObject(barrel,host.id,2300);assert.equal(host.k,kills,'explosion cannot repeat');
  host.x=BOOST_PADS[0][0];host.y=BOOST_PADS[0][1];host.padUntil=0;
  host.inputAt=2400;host.in.mx=1;
  room.sim(2400,0);assert.equal(host.dU,2750,'pad grants movement burst');
  host.energy=999;host.boost=true;room.drop(host.ws);assert.equal(host.boost,false);
  const ws=socket();room.join(ws,host.n,host.tok);
  room.finish();assert.equal(room.teamWinner,0);
  for(let i=0;i<3;i++)room.msg(players[i].ws,{t:'rematch',v:true});
  assert.equal(room.ph,'end','rematch waits for everyone');
  room.msg(players[3].ws,{t:'rematch',v:true});
  assert.equal(room.ph,'count','last rematch vote starts countdown');
  assert.ok(room.objects.every(o=>o.hp>0),'rematch restores objects');
  assert.ok(players.every(p=>p.energy===100 && p.k===0),'rematch resets energy and scores');
  room.ph='lobby';room.configure(host,{map:'neon',minutes:1,target:5,mode:'4v4',difficulty:'easy'});
  room.start(host,3000);assert.equal(room.ph,'lobby','4v4 needs eight players');
  for(let i=0;i<4;i++)room.addBot(host);
  for(const p of room.ps.values())p.ready=true;
  room.start(host,4000);assert.equal(room.ph,'count','4v4 starts with eight players');
  assert.equal([...room.ps.values()].filter(p=>p.team===0).length,4);
  console.log('PASS boost, teams, friendly fire, arena objects, explosions, pads and rematch voting');
}finally{room.destroy();}
